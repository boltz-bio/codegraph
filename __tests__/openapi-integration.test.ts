import { beforeAll, afterEach, describe, expect, it } from 'vitest';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { CodeGraph } from '../src';
import { initGrammars, loadAllGrammars } from '../src/extraction/grammars';
import { ToolHandler } from '../src/mcp/tools';
import { clearProjectConfigCache } from '../src/project-config';
import { parseOpenApiBindings } from '../src/resolution/openapi-config';

let root: string;
let cg: CodeGraph;
const operationPath = '/compute/internal/v1/runs/{id}/stop';
const binding = {
  service: 'compute', schema: 'api/openapi.json', clients: ['backend/sdk.gen.ts'],
  routes: [{ directory: 'api/routes', prefix: '/compute/internal/v1' }],
};
function write(file: string, content: string): void {
  fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
  fs.writeFileSync(path.join(root, file), content);
}
function config(bindings: unknown[] = [binding]): void {
  write('codegraph.json', JSON.stringify({ include: ['backend/sdk.gen.ts'], openapi: bindings }));
  clearProjectConfigCache();
}
function schema(enabled = true, method = 'post'): void {
  write('api/openapi.json', JSON.stringify({ openapi: '3.1.0', paths: enabled ? {
    [operationPath]: { [method]: { operationId: 'stopRun', responses: {} } },
  } : {} }));
}
function route(handler = 'handleStop', url = '/runs/:id/stop'): string {
  return `export async function ${handler}(request) { return request.params.id; }
export async function registerRoutes(fastify) {
  fastify.post('${url}', { schema: { body: {} } }, ${handler});
}
`;
}
function sdk(url = operationPath): string {
  return `// This file is auto-generated by @hey-api/openapi-ts
import { client } from './client';
export const stopRun = <ThrowOnError extends boolean = false>(options: Options<Data, ThrowOnError>): Result<Data, Error, ThrowOnError> => (options.client ?? client).post<Data, Error, ThrowOnError>({
  url: '${url}',
  ...options,
  headers: { 'Content-Type': 'application/json', ...options.headers }
});
`;
}
async function setup(extra?: () => void): Promise<void> {
  root = fs.mkdtempSync(path.join(os.tmpdir(), 'cg-openapi-'));
  write('package.json', JSON.stringify({ dependencies: { fastify: '5' } }));
  write('.gitignore', 'backend/sdk.gen.ts\napi/openapi.json\n');
  config(); schema();
  write('backend/sdk.gen.ts', sdk());
  write('backend/client.ts', 'export const client = {};');
  write('backend/activity.ts', `import { stopRun } from './sdk.gen';
export async function stopActivity() { return stopRun({ path: { id: 'abc' } }); }
`);
  write('api/routes/runs.ts', route());
  extra?.();
  cg = await CodeGraph.init(root, { index: true });
}
function node(name: string) {
  const found = cg.getNodesByName(name).find(n => n.kind === 'function');
  if (!found) throw new Error(`missing function ${name}`);
  return found;
}
function httpEdges() {
  return cg.getCallees(node('stopRun').id).map(c => c.edge).filter(e => e.metadata?.synthesizedBy === 'openapi-client');
}
beforeAll(async () => { await initGrammars(); await loadAllGrammars(); });
afterEach(() => {
  cg?.close();
  if (root) fs.rmSync(root, { recursive: true, force: true });
});

describe('OpenAPI generated clients through native CodeGraph queries', () => {
  it('connects caller, SDK, prefixed route, and handler; surfaces flow and impact', async () => {
    await setup();
    const flow = cg.findPath(node('stopActivity').id, node('handleStop').id, ['calls', 'references']);
    expect(flow?.map(h => h.node.name)).toEqual(['stopActivity', 'stopRun', 'POST /runs/:id/stop', 'handleStop']);
    expect(httpEdges()).toHaveLength(1);
    expect(httpEdges()[0]?.metadata).toMatchObject({ channel: 'http', service: 'compute', operationId: 'stopRun' });
    expect([...cg.getImpactRadius(node('handleStop').id, 3).nodes.values()].map(n => n.name)).toContain('stopActivity');
    const result = await new ToolHandler(cg).execute('codegraph_explore', { query: 'stopActivity stopRun handleStop' });
    const text = result.content.map(c => c.type === 'text' ? c.text : '').join('\n');
    expect(text).toContain('Flow');
    expect(text).toContain('dynamic: HTTP POST');
    expect(text).toContain('→ compute (OpenAPI; configured default, overrides possible)');
  });

  it('isolates identical routes in other services and rejects two matching routes in the configured service', async () => {
    await setup(() => write('other/routes/runs.ts', route('otherStop')));
    expect(httpEdges()).toHaveLength(1);
    expect(cg.findPath(node('stopRun').id, node('otherStop').id, ['calls', 'references'])).toBeNull();
    write('api/routes/duplicate.ts', route('duplicateStop'));
    await cg.sync();
    expect(httpEdges()).toHaveLength(0);
    fs.unlinkSync(path.join(root, 'api/routes/duplicate.ts'));
    await cg.sync();
    expect(httpEdges()).toHaveLength(1);
  });

  it('removes stale edges for schema-only edits, wrong verbs, invalid/missing schemas, and restores them', async () => {
    await setup();
    for (const change of [() => schema(false), () => schema(true, 'get'),
      () => write('api/openapi.json', '{broken'), () => fs.unlinkSync(path.join(root, 'api/openapi.json'))]) {
      change(); await cg.sync(); expect(httpEdges()).toHaveLength(0);
      schema(); await cg.sync(); expect(httpEdges()).toHaveLength(1);
    }
  });

  it('refreshes on route and generated-client edits, handler rename, and route deletion', async () => {
    await setup();
    write('api/routes/runs.ts', route('handleRenamed'));
    await cg.sync();
    expect(cg.findPath(node('stopActivity').id, node('handleRenamed').id, ['calls', 'references'])).not.toBeNull();
    write('api/routes/runs.ts', route('handleRenamed', '/runs/:id/finish'));
    await cg.sync(); expect(httpEdges()).toHaveLength(0);
    write('api/routes/runs.ts', route()); await cg.sync(); expect(httpEdges()).toHaveLength(1);
    write('backend/sdk.gen.ts', sdk('/unmatched')); await cg.sync(); expect(httpEdges()).toHaveLength(0);
    write('backend/sdk.gen.ts', sdk()); await cg.sync(); expect(httpEdges()).toHaveLength(1);
    fs.unlinkSync(path.join(root, 'api/routes/runs.ts')); await cg.sync(); expect(httpEdges()).toHaveLength(0);
  });

  it('does not guess when configuration is removed, mounts disagree, or client service bindings conflict', async () => {
    await setup(() => write('other/routes/runs.ts', route('otherStop')));
    config([binding, { ...binding, service: 'other', routes: [{ directory: 'other/routes', prefix: '/compute/internal/v1' }] }]);
    await cg.sync(); expect(httpEdges()).toHaveLength(0);
    config([{ ...binding, routes: [{ directory: 'api/routes', prefix: '/wrong' }] }]);
    await cg.sync(); expect(httpEdges()).toHaveLength(0);
    config(); await cg.sync(); expect(httpEdges()).toHaveLength(1);
    config([]); await cg.sync(); expect(httpEdges()).toHaveLength(0);
  });

  it('keeps edge count stable on repeat indexing and after reopen', async () => {
    await setup();
    await cg.indexAll(); expect(httpEdges()).toHaveLength(1);
    cg.close(); cg = CodeGraph.openSync(root);
    await cg.sync(); expect(httpEdges()).toHaveLength(1);
  });

  it('watches ignored JSON contract edits and removals without a manual sync', async () => {
    await setup();
    expect(cg.watch({ debounceMs: 50 })).toBe(true);
    await cg.waitUntilWatcherReady();
    schema(false);
    await expect.poll(() => httpEdges().length, { timeout: 10000 }).toBe(0);
    schema();
    await expect.poll(() => httpEdges().length, { timeout: 10000 }).toBe(1);
    fs.unlinkSync(path.join(root, 'api/openapi.json'));
    await expect.poll(() => httpEdges().length, { timeout: 10000 }).toBe(0);
  }, 35000);

  it('requires a generated client marker and a static request URL', async () => {
    await setup(() => write('backend/sdk.gen.ts', sdk().replace('// This file is auto-generated by @hey-api/openapi-ts', '')));
    expect(httpEdges()).toHaveLength(0);
    write('backend/sdk.gen.ts', sdk().replace(`'${operationPath}'`, 'options.url'));
    await cg.sync(); expect(httpEdges()).toHaveLength(0);
  });

  it('keeps the named Fastify handler when route options contain a callback', async () => {
    await setup(() => write('api/routes/runs.ts', route().replace('body: {}', 'body: { transform: (value) => value }')));
    expect(cg.findPath(node('stopActivity').id, node('handleStop').id, ['calls'])).not.toBeNull();
  });

  it('rejects ambiguous normalized contract paths', async () => {
    await setup(() => write('api/openapi.json', JSON.stringify({ openapi: '3.1.0', paths: {
      [operationPath]: { post: { responses: {} } },
      '/compute/internal/v1/runs/{runId}/stop': { post: { responses: {} } },
    } })));
    expect(httpEdges()).toHaveLength(0);
  });
});

describe('OpenAPI configuration validation', () => {
  it('accepts explicit local service bindings', () => expect(parseOpenApiBindings([binding])).toEqual([binding]));
  it.each(['../outside.json', '/outside.json', 'https://example.com/api.json', 'C:\\outside.json'])('rejects non-local schema %s', schema => {
    expect(parseOpenApiBindings([{ ...binding, schema }])).toEqual([]);
  });
  it('skips malformed bindings', () => {
    expect(parseOpenApiBindings([null, {}, { ...binding, routes: [{ directory: 'api', prefix: '/:dynamic' }] }])).toEqual([]);
  });
});
