/** Opt-in Hey API client → OpenAPI-backed route edges. No network requests. */
import * as fs from 'fs';
import * as path from 'path';
import type { Edge, Node } from '../types';
import type { ResolutionContext } from './types';
import type { MaybeYield } from './cooperative-yield';
import { loadOpenApiBindings } from '../project-config';
import { stripCommentsForRegex } from './strip-comments';
import { matchBracket, readFields } from './frameworks/object-literal';
import { logWarn } from '../errors';

export const OPENAPI_SYNTHESIZER = 'openapi-client';
const VERBS = new Set(['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS', 'TRACE']);

function normalized(route: string): string {
  return route.replace(/\{[^/{}]+\}|:[\w]+/g, ':param');
}

function inside(file: string, dir: string): boolean {
  return file === dir || file.startsWith(dir + '/');
}

function localRead(root: string, rel: string): string | null {
  try {
    const real = fs.realpathSync(path.resolve(root, rel));
    const delta = path.relative(fs.realpathSync(root), real);
    if (delta.startsWith('..') || path.isAbsolute(delta)) return null;
    return fs.readFileSync(real, 'utf8');
  } catch { return null; }
}

interface Operation { method: string; href: string; operationId?: string }

function operations(raw: string | null): Map<string, Operation[]> | null {
  try {
    const doc = JSON.parse(raw ?? 'null');
    if (!doc || !/^3\./.test(doc.openapi) || !doc.paths || typeof doc.paths !== 'object') return null;
    const result = new Map<string, Operation[]>();
    for (const [href, item] of Object.entries(doc.paths)) {
      if (!href.startsWith('/') || !item || typeof item !== 'object') continue;
      for (const [verb, op] of Object.entries(item)) {
        const method = verb.toUpperCase();
        if (!VERBS.has(method) || !op || typeof op !== 'object' || '$ref' in op) continue;
        const operationId = 'operationId' in op && typeof op.operationId === 'string' ? op.operationId : undefined;
        const key = `${method} ${normalized(href)}`;
        const entries = result.get(key) ?? [];
        entries.push({ method, href, operationId });
        result.set(key, entries);
      }
    }
    return result;
  } catch { return null; }
}

/** Strictly the generated expression-bodied Hey API request shape. */
function clientOperation(body: string): { method: string; href: string } | null {
  const head = /=>\s*\(\s*([\w$]+)\.client\s*\?\?\s*[\w$]+\s*\)\s*\.\s*(get|post|put|patch|delete|head|options|trace)\s*(?:<[^;]*?>)?\s*\(\s*\{/.exec(body);
  if (!head) return null;
  const open = head.index + head[0].length - 1;
  const close = matchBracket(body, open);
  if (close < 0) return null;
  const url = readFields(body, open, close).get('url')?.text.trim();
  const literal = url && /^(['"])(\/[^'"`\\]*)\1$/.exec(url);
  if (!literal) return null;
  return { method: head[2]!.toUpperCase(), href: literal[2]! };
}

export async function openApiEdges(ctx: ResolutionContext, onYield: MaybeYield): Promise<Edge[]> {
  const bindings = loadOpenApiBindings(ctx.getProjectRoot());
  if (!bindings.length) return [];
  const routes = ctx.getNodesByKind('route');
  // Overlapping bindings with different destinations must not choose a winner.
  const candidates = new Map<string, Map<string, Edge>>();
  for (const binding of bindings) {
    const contract = operations(localRead(ctx.getProjectRoot(), binding.schema));
    if (!contract) {
      logWarn('OpenAPI binding has no readable OpenAPI 3 JSON contract', { service: binding.service, schema: binding.schema });
      continue;
    }
    const routeTable = new Map<string, Map<string, Node>>();
    for (const route of routes) {
      const match = /^([A-Z]+) (\/.*)$/.exec(route.name);
      if (!match || !VERBS.has(match[1]!)) continue;
      for (const mount of binding.routes) {
        if (!inside(route.filePath, mount.directory)) continue;
        const prefix = mount.prefix.replace(/\/$/, '');
        const full = prefix && !inside(match[2]!, prefix) ? prefix + match[2] : match[2]!;
        const key = `${match[1]} ${normalized(full)}`;
        const matches = routeTable.get(key) ?? new Map<string, Node>();
        matches.set(route.id, route);
        routeTable.set(key, matches);
      }
    }
    for (const file of binding.clients) {
      await onYield();
      const functions = ctx.getNodesInFile(file).filter(node => node.kind === 'function');
      if (!functions.length) continue;
      const raw = ctx.readFile(file);
      if (!raw || !/^\/\/ This file is auto-generated by @hey-api\/openapi-ts\b/m.test(raw)) continue;
      const lines = stripCommentsForRegex(raw, 'typescript').split('\n');
      for (const node of functions) {
        const op = clientOperation(lines.slice(node.startLine - 1, node.endLine).join('\n'));
        if (!op) continue;
        const key = `${op.method} ${normalized(op.href)}`;
        const matches = contract.get(key);
        if (matches?.length !== 1) continue;
        const routeMatches = routeTable.get(key);
        // Keep ambiguity across ALL bindings visible to the final uniqueness gate.
        if (!routeMatches?.size) continue;
        const byTarget = candidates.get(node.id) ?? new Map<string, Edge>();
        for (const route of routeMatches.values()) {
          byTarget.set(`${binding.service}:${route.id}`, {
            source: node.id, target: route.id, kind: 'calls', line: node.startLine, column: node.startColumn,
            provenance: 'heuristic',
            metadata: {
              synthesizedBy: OPENAPI_SYNTHESIZER, channel: 'http', tier: 'client→server',
              service: binding.service, method: op.method, href: op.href, operationId: matches[0]!.operationId,
              contract: `${binding.schema}#/paths/${matches[0]!.href.replace(/~/g, '~0').replace(/\//g, '~1')}/${op.method.toLowerCase()}`,
              registeredAt: `${route.filePath}:${route.startLine}`,
              evidence: 'configured-service-and-prefix+openapi+generated-client+route',
              runtimeOverrides: 'client, baseUrl, or url options can change the runtime destination',
            },
          });
        }
        candidates.set(node.id, byTarget);
      }
    }
  }
  return [...candidates.values()].filter(targets => targets.size === 1).map(targets => [...targets.values()][0]!);
}
